const jwt = require('jsonwebtoken');
const User = require('../models/User');
const Village = require('../models/Village');
const Otp = require('../models/Otp');
const { generateCode, sendOtp } = require('../utils/otpService');

const OTP_TTL_MINUTES = 5;
const COOKIE_MAX_AGE = 7 * 24 * 60 * 60 * 1000; // 7 days

function signToken(user) {
  return jwt.sign({ id: user._id, role: user.role }, process.env.JWT_SECRET, { expiresIn: '7d' });
}

// GET /login
exports.showLogin = (req, res) => {
  res.render('login', { title: 'Login', error: null });
};

// GET /register
exports.showRegister = async (req, res) => {
  const villages = await Village.find().sort({ villageName: 1 });
  const mobileNumber = req.query.mobile || '';
  res.render('register', { title: 'Worker Registration', villages, error: null, mobileNumber });
};

// POST /api/v1/auth/send-otp
// Body: { mobileNumber }
exports.sendOtp = async (req, res) => {
  try {
    const { mobileNumber } = req.body;
    if (!mobileNumber || !/^\d{10}$/.test(mobileNumber)) {
      return res.status(400).json({ error: 'Enter a valid 10-digit mobile number.' });
    }

    const code = generateCode();
    const expiresAt = new Date(Date.now() + OTP_TTL_MINUTES * 60 * 1000);

    // Generated by GitHub Copilot - Oct-17-2026
    // A failed provider request must not leave a usable challenge behind.
    const challenge = await Otp.create({ mobileNumber, code, expiresAt, consumed: true });
    const result = await sendOtp(mobileNumber, code);
    challenge.consumed = false;
    await challenge.save();

    // In dev/console mode we surface the code in the API response so the demo
    // works without a real SMS provider. Real deployments (OTP_MODE=twilio)
    // will not leak the code here.
    res.json({
      message: 'OTP dispatched.',
      devCode: result.mode === 'console' ? result.devCode : undefined
    });
  } catch (err) {
    console.error(err);
    res.status(500).json({ error: 'Failed to send OTP.' });
  }
};

// POST /api/v1/auth/verify-otp
// Body: { mobileNumber, code }
// If the mobile number belongs to an existing verified user -> logs them in.
// If not -> tells the frontend to proceed to registration.
exports.verifyOtp = async (req, res) => {
  try {
    const { mobileNumber, code } = req.body;
    if (!mobileNumber || !code) {
      return res.status(400).json({ error: 'Mobile number and OTP are required.' });
    }

    const otpDoc = await Otp.findOne({ mobileNumber, code, consumed: false }).sort({ createdAt: -1 });
    if (!otpDoc) {
      return res.status(400).json({ error: 'Invalid OTP.' });
    }
    if (otpDoc.expiresAt < new Date()) {
      return res.status(400).json({ error: 'OTP has expired. Please request a new one.' });
    }

    otpDoc.consumed = true;
    await otpDoc.save();

    const existingUser = await User.findOne({ mobileNumber });

    if (!existingUser) {
      // New number -> needs registration/profile linking (Module 1.2)
      return res.json({ status: 'new_user', mobileNumber });
    }

    const token = signToken(existingUser);
    res.cookie('token', token, { httpOnly: true, maxAge: COOKIE_MAX_AGE, sameSite: 'lax' });

    const redirectUrl = ['admin', 'mla'].includes(existingUser.role) ? '/admin/dashboard' : '/dashboard';
    res.json({ status: 'logged_in', redirectUrl });
  } catch (err) {
    console.error(err);
    res.status(500).json({ error: 'OTP verification failed.' });
  }
};

// POST /api/v1/auth/register
// Body: { mobileNumber, fullName, whatsappNumber, designation, villageId, role }
exports.register = async (req, res) => {
  try {
    const { mobileNumber, fullName, whatsappNumber, designation, villageId, role } = req.body;

    if (!mobileNumber || !fullName || !villageId) {
      return res.status(400).json({ error: 'Full name, mobile number, and village are required.' });
    }

    const village = await Village.findById(villageId);
    if (!village) {
      return res.status(400).json({ error: 'Selected village not found.' });
    }

    const allowedSelfRoles = ['worker', 'sarpanch'];
    const finalRole = allowedSelfRoles.includes(role) ? role : 'worker';

    let user = await User.findOne({ mobileNumber });
    if (user) {
      return res.status(400).json({ error: 'This mobile number is already registered. Please log in.' });
    }

    user = await User.create({
      fullName,
      mobileNumber,
      whatsappNumber,
      designation,
      village: village._id,
      role: finalRole,
      isVerified: false // flagged for admin review per Module 1.3
    });

    const token = signToken(user);
    res.cookie('token', token, { httpOnly: true, maxAge: COOKIE_MAX_AGE, sameSite: 'lax' });
    res.json({ status: 'registered', redirectUrl: '/dashboard' });
  } catch (err) {
    console.error(err);
    res.status(500).json({ error: 'Registration failed.' });
  }
};

// GET /logout
exports.logout = (req, res) => {
  res.clearCookie('token');
  res.redirect('/login');
};

// GET /api/v1/auth/me - returns the logged-in user's profile.
// Used by the Android app on launch to silently restore a session from the
// stored cookie (and to know which role's home screen to show).
exports.me = (req, res) => {
  res.json({ user: req.user });
};
